#!/usr/bin/env bash
# First install: run inside the extracted offline package directory  bash install.sh --dir /opt/wms [options]
# See docs/deployment.md for details
set -euo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "$0")/scripts/lib.sh"
PKG_DIR=$(abspath "$(dirname "$0")")

usage() {
  cat <<'EOF'
Usage: bash install.sh --dir INSTALL_DIR [options]

  --dir DIR              Install directory (default /opt/wms) for settings, backups and state
  --company NAME         Company name (default "Default company")
  --tenant-code CODE     Tenant code (default DEFAULT)
  --preset NAME          Industry preset: standard / distribution / 3pl (default standard)
  --http-port PORT       Access port (default 80)
  --project NAME         Distinguishes several instances on one server (default wms)
  --external-db URL      Use the customer's own SQL Server; SQLAlchemy URL such as
                         'mssql+pyodbc://wms:PASSWORD@10.0.0.5:1433/wms?driver=ODBC+Driver+18+for+SQL+Server&TrustServerCertificate=yes'
  --backup-dir PATH      Required with your own SQL Server: backup directory on the database server
  --mssql-pid PID        Edition/license of the bundled SQL Server (default Express)
  --admin-password PWD   Initial admin password (randomly generated by default)
EOF
}

WMS_DIR=/opt/wms COMPANY="Default company" TENANT_CODE=DEFAULT PRESET=standard HTTP_PORT=80 PROJECT=wms
EXTERNAL_DB="" BACKUP_DIR_ARG="" MSSQL_PID=Express ADMIN_PASSWORD=""
while [ $# -gt 0 ]; do
  case $1 in
    --dir) WMS_DIR=$2; shift 2 ;;
    --company) COMPANY=$2; shift 2 ;;
    --tenant-code) TENANT_CODE=$2; shift 2 ;;
    --preset) PRESET=$2; shift 2 ;;
    --http-port) HTTP_PORT=$2; shift 2 ;;
    --project) PROJECT=$2; shift 2 ;;
    --external-db) EXTERNAL_DB=$2; shift 2 ;;
    --backup-dir) BACKUP_DIR_ARG=$2; shift 2 ;;
    --mssql-pid) MSSQL_PID=$2; shift 2 ;;
    --admin-password) ADMIN_PASSWORD=$2; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) usage; die "Unknown argument: $1" ;;
  esac
done

START=$(date +%s)
VERSION=$(cat "$PKG_DIR/VERSION")
[ -n "$EXTERNAL_DB" ] && [ -z "$BACKUP_DIR_ARG" ] && die "With your own SQL Server, --backup-dir must give the backup directory on the database server"
case $COMPANY in *[\"\'\$\`]*) die "Company name cannot contain quotes, \$ or backticks" ;; esac
[ -e "$WMS_DIR/.env" ] && die "$WMS_DIR is already installed (.env exists); use upgrade.sh to upgrade"

require_docker

# If a first install fails midway, print how to clean up (fresh installs only: this deletes the instance's database volume)
on_exit() {
  local code=$?
  [ "$code" = 0 ] && return
  warn "Installation did not finish. Find the cause, then clean up and reinstall:"
  warn "  docker compose -p $PROJECT --project-directory $WMS_DIR down -v && rm -rf $WMS_DIR"
}
trap on_exit EXIT

log "Verifying package"
(cd "$PKG_DIR" && sha256sum -c --quiet SHA256SUMS) || die "Package checksum failed; copy the package again"

log "Importing images (offline)"
for f in "$PKG_DIR"/images/*.tar.gz; do
  docker load -i "$f" | sed 's/^/  /'
done

log "Preparing install directory $WMS_DIR"
mkdir -p "$WMS_DIR"/{backups,state,logs,scripts}
WMS_DIR=$(abspath "$WMS_DIR")
cp "$PKG_DIR/docker-compose.yml" "$PKG_DIR/VERSION" "$WMS_DIR/"
cp "$PKG_DIR"/scripts/*.sh "$WMS_DIR/scripts/"

if [ -n "$EXTERNAL_DB" ]; then
  PROFILES="" SA_PASSWORD="" DATABASE_URL=$EXTERNAL_DB BACKUP_DIR=$BACKUP_DIR_ARG
else
  PROFILES=bundled-db
  # SQL Server password complexity: upper and lower case + digits + symbols; only characters that need no escaping in a URL or .env
  SA_PASSWORD="Wms-$(random_hex 12)-9a"
  DATABASE_URL="mssql+pyodbc://sa:${SA_PASSWORD}@db:1433/wms?driver=ODBC+Driver+18+for+SQL+Server&TrustServerCertificate=yes"
  BACKUP_DIR=/var/opt/mssql/backup
  # The database container runs as uid 10001 and must be able to write the backup directory
  if [ "$(id -u)" = 0 ]; then chown 10001:0 "$WMS_DIR/backups"; else chmod 777 "$WMS_DIR/backups"; fi
fi

sed -e "s|__VERSION__|$VERSION|" -e "s|__PROJECT__|$PROJECT|" -e "s|__HTTP_PORT__|$HTTP_PORT|" \
    -e "s|__PROFILES__|$PROFILES|" -e "s|__SA_PASSWORD__|$SA_PASSWORD|" -e "s|__MSSQL_PID__|$MSSQL_PID|" \
    -e "s|__BACKUP_DIR__|$BACKUP_DIR|" -e "s|__JWT_SECRET__|$(random_hex 32)|" \
    -e "s|__TENANT_CODE__|$TENANT_CODE|" -e "s|__TENANT_NAME__|$COMPANY|" -e "s|__PRESET__|$PRESET|" \
    "$PKG_DIR/env.template" >"$WMS_DIR/.env"
# The connection string contains sed special characters such as &, so write it separately
env_set DATABASE_URL "$DATABASE_URL"
chmod 600 "$WMS_DIR/.env"

start_db
backend_run python -m scripts.dbops ensure
log "Creating tables (database migration)"
backend_run alembic upgrade head

[ -n "$ADMIN_PASSWORD" ] || ADMIN_PASSWORD="Admin-$(random_hex 5)"
log "Loading base data (preset $PRESET)"
dc run --rm -T --no-deps -e SEED_ADMIN_PASSWORD="$ADMIN_PASSWORD" backend python -m scripts.seed

log "Starting services"
dc up -d
wait_ready 180 || die "Services did not start properly; send the log above to your implementation contact"

ELAPSED=$(($(date +%s) - START))
printf '%s install %s preset=%s elapsed=%ss\n' "$(date '+%F %T')" "$VERSION" "$PRESET" "$ELAPSED" >>"$WMS_DIR/logs/deploy.log"
umask 077
printf '%s\n' "$ADMIN_PASSWORD" >"$WMS_DIR/state/initial-admin-password"

cat <<EOF

========================================
 Installed: WMS $VERSION (took ${ELAPSED}s)
 URL: http://<this server IP>:$HTTP_PORT
 Admin: admin / $ADMIN_PASSWORD
 (The password is also saved in $WMS_DIR/state/initial-admin-password; delete that file after changing the password at first sign-in)
 PDA server URL: http://<this server IP>:$HTTP_PORT
========================================
EOF
